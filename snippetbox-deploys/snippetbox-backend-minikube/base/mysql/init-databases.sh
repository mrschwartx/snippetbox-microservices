#!/bin/sh

mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS \`$USER_DB_NAME\` CHARACTER SET utf8mb4;
CREATE USER IF NOT EXISTS '$USER_DB_USER'@'%' IDENTIFIED BY '$USER_DB_PASSWORD';
GRANT ALL PRIVILEGES ON \`$USER_DB_NAME\`.* TO '$USER_DB_USER'@'%';

CREATE DATABASE IF NOT EXISTS \`$SNIPPET_DB_NAME\` CHARACTER SET utf8mb4;
CREATE USER IF NOT EXISTS '$SNIPPET_DB_USER'@'%' IDENTIFIED BY '$SNIPPET_DB_PASSWORD';
GRANT ALL PRIVILEGES ON \`$SNIPPET_DB_NAME\`.* TO '$SNIPPET_DB_USER'@'%';

FLUSH PRIVILEGES;
SQL
